// Real browser integration tests, including the iframe WebGPU renderer and
// a download through the HTTP worker. Run web_api_test.py first for the fixture.
import {createRequire} from 'node:module';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.KB_WEB_URL||'http://127.0.0.1:4505/kernelbasher/';
const browser=await chromium.launch(process.env.KB_EDGE_PATH?{executablePath:process.env.KB_EDGE_PATH,headless:true}:{channel:'msedge',headless:true});
const checks=[];
const record=(name,extra={})=>{checks.push({name,passed:true,...extra});console.log(name+': passed');};
try{
    const page=await browser.newPage({viewport:{width:1440,height:1100}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(base);
    await page.waitForFunction(()=>document.getElementById('preview-state').textContent==='LIVE',null,{timeout:30000});
    await page.locator('#preview').evaluate(el=>el.src='preview/index.html?test=1');
    const frame=page.frames().find(f=>f.url().includes('preview/index.html'));
    await frame.waitForFunction(()=>window.previewTest,null,{timeout:30000});
    const seek=ms=>frame.evaluate(ms=>previewTest.seek(ms),ms);
    const pixels=()=>frame.evaluate(async()=>Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',await previewTest.stage.gpu.read()))).join(','));
    await seek(2000);const baseline=await pixels();
    await page.screenshot({path:resolve(root,'evidence/web-desktop.png'),fullPage:true});
    assert.ok(await page.locator('#download').isDisabled());
    record('live preview before loading BIOS');
    await page.locator('#range-6').fill('240');await page.locator('#range-7').fill('10');
    await frame.waitForFunction(()=>previewTest.state().settings.colours[6]===240);
    await seek(2000);assert.notEqual(await pixels(),baseline);record('colour sliders update rendered pixels');
    await page.locator('#tab-motion').click();await page.locator('#radius').fill('1.375');
    await frame.waitForFunction(()=>previewTest.state().settings.radius===1.375);await seek(2000);
    const radiusPixels=await pixels();assert.notEqual(radiusPixels,baseline);record('radius updates renderer');
    await page.locator('#camera').selectOption('8');
    await frame.waitForFunction(()=>previewTest.state().settings.camera===8);await seek(2000);assert.notEqual(await pixels(),radiusPixels);record('camera updates renderer');
    await page.locator('#tab-logo').click();await seek(7000);const noLogo=await pixels();
    await page.locator('#logo-file').setInputFiles(resolve(root,'original/extracted/xfiles/xsguy.x'));
    await frame.waitForFunction(()=>previewTest.state().settings.logo?.vertices.length===348);
    await seek(7000);assert.notEqual(await pixels(),noLogo);
    await page.screenshot({path:resolve(root,'evidence/web-custom-logo.png'),fullPage:true});
    record('X-file selection replaces the visible lettering');
    await frame.evaluate(()=>{previewTest.restart();previewTest.play();});
    await frame.waitForFunction(()=>previewTest.state().cycles>=2,null,{timeout:30000});
    assert.deepEqual(await frame.evaluate(()=>previewTest.state().errors),[]);record('custom X file survives two automatic loops');
    await page.locator('#tab-colours').click();
    await page.locator('#preset-file').setInputFiles(resolve(root,'original/extracted/Presets/RED.kbp'));
    await page.waitForFunction(()=>document.getElementById('toast').textContent==='Preset colours and radius loaded.');
    const downloadPromise=page.waitForEvent('download');await page.locator('#save-preset').click();
    const download=await downloadPromise;const bytes=await readFile(await download.path());
    assert.deepEqual(bytes.subarray(0,80),(await readFile(resolve(root,'original/extracted/Presets/RED.kbp'))).subarray(0,80));
    record('legacy preset colour/radius round trip');
    await page.locator('#bios-file').setInputFiles({name:'bad.bin',mimeType:'application/octet-stream',buffer:Buffer.from('bad')});
    await page.waitForFunction(()=>document.getElementById('bios-help').textContent.includes('256 KiB'));
    assert.ok(await page.locator('#download').isDisabled());record('invalid BIOS cannot be downloaded');
    await page.locator('#bios-file').setInputFiles(resolve(root,'build/web-tests/synthetic-m8.bin'));
    await page.waitForFunction(()=>document.getElementById('bios-chip').textContent==='BIOS LOADED');
    assert.ok(await page.locator('#output-size').isDisabled());assert.ok(await page.locator('#torn').isDisabled());
    await page.locator('#reset').click();
    const resultPromise=page.waitForEvent('download');await page.locator('#download').click();
    const result=await resultPromise;
    assert.deepEqual(await readFile(await result.path()),await readFile(resolve(root,'build/web-tests/windows-0.bin')));
    record('browser download exactly matches the native Windows output');
    // Keyboard tabs stay accessible without requiring pointer input.
    await page.locator('#tab-colours').focus();await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#tab-motion').getAttribute('aria-selected'),'true');record('keyboard tab navigation');
    const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
    await mobile.goto(base);await mobile.waitForFunction(()=>document.getElementById('preview-state').textContent==='LIVE',null,{timeout:30000});
    assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await mobile.screenshot({path:resolve(root,'evidence/web-mobile.png'),fullPage:true});record('390px mobile layout without horizontal overflow');
    await mobile.close();
    const unavailable=await browser.newPage();
    await unavailable.addInitScript(()=>Object.defineProperty(navigator,'gpu',{get:()=>undefined}));
    await unavailable.goto(base);await unavailable.waitForFunction(()=>document.getElementById('preview-state').textContent==='UNAVAILABLE',null,{timeout:30000});
    assert.ok(await unavailable.locator('#range-6').isEnabled());record('clear WebGPU fallback with editor still available');
    await unavailable.close();
    assert.deepEqual(errors,[]);
    await writeFile(resolve(root,'evidence/web-browser-tests.json'),JSON.stringify({base,passed:true,checks},null,2)+'\n');
}finally{await browser.close();}
